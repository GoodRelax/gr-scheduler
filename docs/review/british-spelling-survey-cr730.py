"""Count every British spelling in the tracked tree, by class (CR-730).

change-request/CR-730-one-spelling-american-color-everywhere.md carries the
numbers this prints (section 3) and names this script in section 13.

Usage, from the repository root of a clean tree (it reads `git ls-files`):
    PYTHONIOENCODING=utf-8 python docs/review/british-spelling-survey-cr730.py <out-dir>

<out-dir> must lie OUTSIDE the worktree (OneDrive syncs it, DFC-2312). It gets
hits.tsv (one row per occurrence: path, line, word, sub-word, family, class,
kind). Standard output gets:
  1. the class x family table (section 3.1 of the CR),
  2. the live totals per family (section 3.2),
  3. the distinct-name counts per class,
  4. the public names: GRS JSON schema keys and enum values, MCP tool names,
     Agent API members and commands of table T-107 (classes c and d),
  5. the code-point spellings (String.fromCharCode / fromCodePoint, hex or
     decimal arrays, \\u and \\x escapes, split literals) that spell a word,
  6. the collisions: a British name whose American form is already a token
     of the same file (section 7.3).

Words are matched on SUB-WORDS (camelCase / snake_case / kebab-case split),
so `groupDepthLimitReached` never reads as a British word. The lexer of
tools/rename/lex_spans.mjs (babel, from the node_modules above the tree)
says whether a hit in JS/TS is code, comment, string or regex.
"""
